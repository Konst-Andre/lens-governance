"""G-O крок 4 — §0 п.4 самері G-N: кандидати в чергу ядра (Lens_governance_CHERGA.md).
   живе доки: хід 4 сесії G-O не влитий у репо.
   Ф-10: стеля 8 192 B — детектор вичерпаного жанру; сигнал >90% (7 373 B). Тому заміри з рядка G3-1
   виїжджають у самері (покажчик «Заміри: G-H · G-J §2-б»), а не стискаються.
   Правки: G3-1 += умова G10 з --live (G-J §2-б) · К3-1 += Ф-18 · Ф-19 (дописком, не новим id).
   G22-1 і G6-1 НЕ вписано: з ними черга = 7 879 B (96%) — стоп Ф-10 (виміряно цим скриптом, v0).
   Вони лишаються в §0 самері G-O; шлях закриття — написати гейти, а не займати носій. Дубль 13.2 у PROFILE §4 — НЕ сюди:
   правиться окремим кроком у каноні (як G-N хід 4), черга місця на нього не витрачає.
   Стопи: якорі ×1 (repr), стеля 90% (Ф-10). П34/П37: повтор → exit 0, той самий md5."""
import sys, hashlib
P = sys.argv[1] if len(sys.argv) > 1 else '/home/claude/lgq/kernel/Lens_governance_CHERGA.md'
def die(m): print('✗ СТОП:', m); sys.exit(1)
CEIL, F10 = 8192, int(8192 * 0.9)

G3_OLD = ("| `G3-1` | **`G3` вимагає оголошення архівних файлів** — ✗, який не закрити (`Ф-5`). G-H: **12 із 98**, "
          "+2 за сесію механічно; 12% > порогу 10% (Sadowski) | 18.09.2026 | `G3` виключає `archive/`; ✗ дієві ⟂ фон |")
G3_NEW = ("| `G3-1` | **`G3` вимагає оголошення архівних файлів** — ✗, який не закрити (`Ф-5`); `G10` не бачить живих "
          "самері навіть з `--live`. Заміри: G-H · G-J §2-б | 18.09.2026 | `G3` виключає `archive/`; `G10` з `--live` "
          "резолвить живі; ✗ дієві ⟂ фон |")
K3_OLD = "Вісь — `К4-1`. Текст: `GC2b §2` · `GD §2` · `G-I §2` |"
K3_NEW = ("Вісь — `К4-1`. + сирота-абзац (Ф-18) · `G19` без повного корпусу не виселяє (Ф-19). "
          "Текст: `GC2b §2` · `GD §2` · `G-I §2` · `G-L §2` |")
t = open(P, encoding='utf-8').read()
md = lambda s: hashlib.md5(s.encode()).hexdigest()[:8]
PAIRS = [(G3_OLD, G3_NEW), (K3_OLD, K3_NEW)]
if all(t.count(n) == 1 for _, n in PAIRS) and t.count(G3_OLD) == 0 and t.count(K3_OLD) == 0:
    print(f'✓ вже застосовано (md5 {md(t)}, {len(t.encode())} B) — нічого не пишу'); sys.exit(0)
if not all(t.count(o) == 1 for o, _ in PAIRS):
    die('стан змішаний: ' + repr([t.count(o) for o, _ in PAIRS]))
t2 = t
for o, n in PAIRS:
    t2 = t2.replace(o, n)
n2 = len(t2.encode())
if n2 > F10: die(f'Ф-10: {n2} B > {F10} B (90% стелі) — жанр вичерпано, не дописувати')
open(P, 'w', encoding='utf-8').write(t2)
print(f'✓ черга {len(t.encode())} → {n2} B ({n2*100/CEIL:.1f}% стелі; межа Ф-10 {F10}) · md5 {md(t)} → {md(t2)}')
print('✓ G3-1 += G10 --live · К3-1 += Ф-18/Ф-19 (нових id немає)')
