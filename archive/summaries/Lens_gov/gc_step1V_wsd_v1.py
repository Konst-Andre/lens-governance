#!/usr/bin/env python3
# G-C · група В · Д-7 → wsd 1.20 (+ вісь 6 у 1.9) · Д-8 → wsd 2.15 · Д-9 → wsd 4.5
# живе доки: G-C закрито й запушено (пакет сесії, потім архів)
import sys, hashlib
W = "kernel/wsd/Work_Standard.md"; B = "kernel/wsd/wsd_delta_running.md"
w = open(W, encoding="utf-8").read(); b = open(B, encoding="utf-8").read()
md5 = lambda s: hashlib.md5(s.encode()).hexdigest()[:8]
M = ["## 1.20 Нова візуальна ідея звіряється з `Lens_cookbook_INDEX.md` ДО пропозиції",
     "## 2.15 Device-тест дефектної збірки не є тестом — вирок анулюється явно",
     "## 4.5 Проба важелями називає **носія**, вирок про **корінь** — окремий крок",
     "|6|**канон**|"]
MB = "| Д-7 звірка ідеї з Cookbook INDEX |"
done = [m in w for m in M] + [MB in b]
if all(done): print("no-op", md5(w), md5(b)); sys.exit(0)
assert not any(done), f"частковий стан {done} — стоп"
print("до", md5(w), md5(b))
def cut(s, h, n):
    assert s.count(h) == 1 and s.count(n) == 1, f"якір {h[:25]} — стоп"
    i, j = s.index(h), s.index(n); assert i < j; return s[i:j]
H7 = "## Д-7 · Нова візуальна ідея звіряється з `Lens_cookbook_INDEX.md` ДО пропозиції\n"
H9 = "## Д-9 · Проба важелями називає **носія**, вирок про **корінь** — окремий крок\n"
H10 = "## Д-8 · Device-тест дефектної збірки не є тестом — вирок анулюється явно\n"
H12 = "## ✅ `1.15` (доповнення)"
d7 = cut(b, H7, H9)
assert b.count("\n## Д-10") == 0
# після групи Б порядок: Д-7, Д-9, Д-8, ✅1.15
d9 = cut(b, H9, H10); d8 = cut(b, H10, H12)
body = lambda blk, h: blk[len(h):].strip().rstrip("-").strip() + "\n"
b7, b9, b8 = body(d7, H7), body(d9, H9), body(d8, H10)
tag = "\n*(Злито G-C 17.09.2026 з буфера `{}`.)*\n"

# 1.20 — після 1.19-б
A = "Злито G-C 17.09.2026 (урізаний за `12.18`).\n"
assert w.count(A) == 1
w = w.replace(A, A + "\n\n-----\n\n" + M[0] + "\n\n" + b7 +
  "\n**Розмежування.** `1.9` вісь 6 — перевірка **плану** перед погодженням; `1.20` — момент **раніше**: ідея ще не названа вголос. `12.17` — те саме для записів канону при вливанні.\n"
  + tag.format("Д-7"))
# вісь 6 у 1.9
A5 = "|5|**маршрут**|для кожної нової сутності — дім за 12.11 названо? Чи не вигадано новий дім там, де старий уже названий у джерелі?|\n"
assert w.count(A5) == 1
w = w.replace(A5, A5 + "|6|**канон**|нова ідея / патерн / правило — звірено з індексом канону (`Lens_cookbook_INDEX.md` · `12.17`)? Рядок «звірено з INDEX: немає / A**» стоїть? *(1.20)*|\n")
# 2.15 — після 2.14
A14 = "*(Злито G-C 17.09.2026 з буфера `Д-10`, урізаний за `12.18`.)*\n"
assert w.count(A14) == 1
w = w.replace(A14, A14 + "\n-----\n\n" + M[1] + "\n\n" + b8 +
  "\n**Розмежування.** `2.5` форма B анулює вердикт, коли **в тій самій відповіді** змінився другий член пари — предмет суду інший. `2.15` анулює, коли дефектною виявилась **збірка**, на якій судилось. `12.9` — канон лише після device; `2.15` — не всякий device є device.\n"
  + tag.format("Д-8"))
# 4.5 — кінець кластера 4
AC5 = "\n-----\n\n\n# Кластери 5–6"
assert w.count(AC5) == 1
w = w.replace(AC5, "\n-----\n\n" + M[2] + "\n\n" + b9 +
  "\n**Розмежування.** `4.1` крок 3–4 — гіпотеза причини перевіряється на даних; `4.5` — проба, що **вмикає й вимикає** симптом, дає лише носія, а не підтверджену гіпотезу. Сусід `2.14`: носієм буває сам стенд.\n"
  + tag.format("Д-9") + AC5)

for blk in (d7, d9, d8): b = b.replace(blk, "")
LO = "**ЛОТОК: 5 записів.** *(2 покажчики: З-42 · В-15 + 3 повних: Д-7 · Д-8 · Д-9 · G-C 17.09.2026:"
LN = "**ЛОТОК: 2 записів.** *(2 покажчики: З-42 · В-15 · G-C 17.09.2026: В Д-7 → 1.20 · Д-8 → 2.15 · Д-9 → 4.5 ·"
RA = "Дім виявився не `Work_Standard`, а маршрутизатор:"
assert b.count(LO) == 1 and b.count(RA) == 1
b = b.replace(LO, LN).replace(RA,
 "**Група В — нові, злито як є (+ розмежування):**\n\n| запис | став у wsd |\n|---|---|\n"
 + MB + " **1.20** + вісь 6 у `1.9` |\n| Д-8 анулювання device-вироку | **2.15** |\n| Д-9 носій ≠ корінь | **4.5** |\n\n" + RA)
open(W, "w", encoding="utf-8").write(w); open(B, "w", encoding="utf-8").write(b)
print("після", md5(w), md5(b))
