P = sys.argv[1] if len(sys.argv) > 1 else '/home/claude/lgx/kernel/wsd/Lens_governance_protocol.md'
def die(m): print('✗ СТОП:', m); sys.exit(1)
md = lambda s: hashlib.md5(s.encode()).hexdigest()[:8]

ANCH = "Прецедент механізму — С2 (G-K, `655521b`: 8 414 B, md5 звірено до і після запису).\n"
ADD = (
 "\n**Доказ — позиційний, не пошуковий (Ф-20, G-M; влито G-P 18.09.2026).** Коли між перенесеними фрагментами\n"
 "стоїть **новий** текст (примітка, розділювач-склейка), `md5(вставлене) == md5(вирізане)` рахується вирізанням\n"
 "нового тексту **за відомою позицією** (зсув = сума довжин попередніх фрагментів) з перевіркою, що на тій\n"
 "позиції лежить саме він, — не `replace(новий_текст, '', 1)`. Те саме для вставки нового тексту в канон:\n"
 "доказ — `revert(new, k) == old` за позицією вставки (G-O, ходи 2 · 3 · 5 · 6). **Чому:** G-M хід 2 —\n"
 "склейка `\\n-----\\n\\n` траплялась усередині фрагмента 1, `replace` вирізав її звідти, доказ дав хибний ✗ на\n"
 "правильному збиранні; G-O хід 2 — пошук роздільника `-----` зловив не той екземпляр. Це пастка `1.15` №3\n"
 "(збіг по підрядку ≠ збіг сутності) у самому доказі. **Детектор:** `replace` або пошук якоря на рядку доказу\n"
 "md5/revert у скрипті з новим текстом → ✗; позиційна функція з assert «на місці» → ✓.\n"
 "\n**Рішення затвердженого плану — до кінця розділу, до збирання кроку (Ф-17, G-L; влито G-P 18.09.2026).**\n"
 "Крок, що виконує план попередньої сесії, спершу читає розділ плану **цілком, разом із блоком «Рішення»**,\n"
 "і в мікроскопі кроку називає, які рішення плану він виконує (напр. «маршрут — таблиця, рішення (а)»).\n"
 "Прецедент реалізації (старий шаблон) рішення плану не замінює. **Чому:** G-L у С3 зробила маршрут заглушками\n"
 "на кожне правило за прецедентом `12.15–12.19`, хоча G-J §3 (а) вирішила «одна таблиця» з гейтовою підставою\n"
 "(`_rule_ids` рахує заглушки, `G19` підписав би 13.x домом `(wsd)`). Гейт не впав — помилку знайшла\n"
 "перепровірка, виправлено в `bf606d1`. **Детектор:** мікроскоп кроку плану без рядка «рішення плану: …» → ✗\n"
 "при самоперегляді; механічний кандидат — у `wsd` заголовок `## N.N`, чиє тіло лише веде в інший файл\n"
 "`RULE_FILES` крім gov (заглушки S14 — названий виняток) → ⚠ «заглушка замість таблиці».\n")

t = open(P, encoding='utf-8').read()
if t.count(ANCH + ADD) == 1:
    print(f'✓ вже застосовано (md5 {md(t)}) — нічого не пишу'); sys.exit(0)
if t.count(ANCH) != 1: die(f'якір count={t.count(ANCH)} · {ANCH!r}')
if t.count('Ф-20') or t.count('Ф-17'): die('Ф-17/Ф-20 уже згадані — стан змішаний')
