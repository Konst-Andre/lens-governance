"""G-N крок 3 — С6 розпилу wsd (К6-1), частина 2: рядок «читається коли: … · не читається: …»
   у шапки 10 канон-файлів без тригера (G23 ✗10 → 0). Рядок — одразу під «живе доки», у тій же цитаті.
   Тригер — одна з п'яти точок паузи (G-G §4). Тексти описують фактичне вживання файлу, не нову політику.
   16 файлів з вільною формою тригера не нормалізуються (стиль ≠ дірка).
   живе доки: хід 3 сесії G-N не влитий у репо.
   12.16: стопи вище запису · П34/П37: повтор → exit 0, той самий md5."""
import sys, os
STG = sys.argv[1] if len(sys.argv) > 1 else '/home/claude/lgx'
def die(m): print('✗ СТОП:', m); sys.exit(1)
P = '> читається коли: '
T = [
 ('kernel/Lens_ARCHIVE_INDEX.md', '> живе доки: назавжди (вічне, wsd 1.8)\n',
  'мікроскоп перед кодом — хід архівує файли або шукає архівне джерело · не читається: на старті сесії; цілком'),
 ('kernel/Lens_NEWPROJECT_bootstrap.md', '> живе доки: назавжди (вічне, wsd 1.8)\n',
  'старт сесії — лише коли заводиться новий Project · не читається: у робочій сесії продукту чи governance'),
 ('kernel/Lens_PROJECT_instruction.md', '> живе доки: назавжди (вічне, wsd 1.8) — оновлюється при зміні протоколу старту\n',
  'мікроскоп перед кодом — хід міняє протокол старту · не читається: на старті сесії (текст уже в полі Instructions)'),
 ('kernel/Lens_fx_candidates.md', '> живе доки: назавжди (вічне, wsd 1.8) — реєстр ЗОВНІШНІХ ефектів; наше й device-locked → Cookbook\n',
  'мікроскоп перед кодом — задача бере зовнішній візуальний ефект · не читається: на старті сесії; наше й device-locked — у Cookbook'),
 ('kernel/Lens_governance_CHERGA.md', '> живе доки: назавжди (носій відкритого по governance, wsd 1.8)\n',
  'старт сесії — у governance-сесії, цілком · перед самері — прополка · не читається: у продуктовій сесії'),
 ('kernel/Lens_sandbox_manifest.md', '> живе доки: назавжди (вічне, wsd 1.8) — метод роботи, не код продукту\n',
  'мікроскоп перед кодом — будується пісочниця (device-тест на синтетичних даних) · не читається: на старті сесії; у звичайному білді'),
 ('kernel/Lens_stagebench_manifest.md', '> живе доки: назавжди (вічне, wsd 1.8) — метод роботи, не код продукту\n',
  'мікроскоп перед кодом — будується чи правиться стенд · не читається: на старті сесії; цілком'),
 ('kernel/Lens_stagebench_delta_running.md', '> живе доки: доки записи не змерджено у `Lens_stagebench_manifest.md` (буфер, wsd 1.8) · стеля 2–3 сесії\n',
  'перед самері — дописується знахідка стенду · мікроскоп перед кодом — мердж у маніфест · не читається: на старті сесії'),
 ('kernel/cookbook/Lens_cookbook_delta_running.md', '> живе доки: назавжди — це **вічний лоток**, а не тимчасовий файл. Порожній = норма.\n',
  'перед самері — дописується знахідка UI/iOS · мікроскоп перед кодом — мердж у том · не читається: на старті сесії'),
 ('kernel/wsd/wsd_delta_running.md', '> живе доки: доки записи не змерджено у `Work_Standard.md` (буфер, wsd 1.8) · стеля 2–3 сесії\n',
  'перед самері — дописується нове правило · мікроскоп перед кодом — мердж у дім правила · не читається: на старті сесії'),
]
src, st = {}, []
for f, a, line in T:
    p = os.path.join(STG, f); t = open(p, encoding='utf-8').read(); src[f] = t
    n = a + P + line + '\n'
    if t.count(n) == 1: st.append('new'); continue
    if t.count(a) != 1: die(f'{f}: якір «живе доки» ×{t.count(a)} ({a!r})')
    if '\n'.join(t.splitlines()[:12]).count('читається') or 'AUTO-READ' in '\n'.join(t.splitlines()[:12]):
        die(f'{f}: у шапці вже є тригер')
    st.append('old')
if set(st) == {'new'}: print('✓ вже застосовано — нічого не пишу'); sys.exit(0)
if set(st) != {'old'}: die(f'стан змішаний: {st}')
for f, a, line in T:
    t2 = src[f].replace(a, a + P + line + '\n', 1)
    open(os.path.join(STG, f), 'w', encoding='utf-8').write(t2)
    print(f'✓ {f}: {len(src[f].encode()):6d} → {len(t2.encode()):6d} B')
