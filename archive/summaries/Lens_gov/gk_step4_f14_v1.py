#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""G-K крок 4 — Ф-14 (самері G-J §2) вливається в 12.16 gov-протоколу: виняток з «Межі 🔒»
   для переносу байт-у-байт + рядок детектора.
   живе доки: хід 4 G-K не влитий у репо.
   12.16 прочитано цілком (G-K хід 4). Дописування за якорем count==1, стопи вище запису.
   П34/П37: повтор → exit 0."""
import sys, os
STG = sys.argv[1] if len(sys.argv) > 1 else '/home/claude/lgx'
P = os.path.join(STG, 'kernel/wsd/Lens_governance_protocol.md')
def die(m): print('✗ СТОП:', m); sys.exit(1)

A1 = ('поштучного погодження **до** запуску; виконується тим самим скриптом за якорем, з read-back.\n')
N1 = ('\n**Виняток з межі — перенос байт-у-байт (Ф-14, G-J; влито G-K 18.09.2026).** Коли фрагмент '
      '**переноситься без зміни жодного байта** з одного файлу канону в інший (розпил за жанрами, `IDX-7`), '
      'читання цілком не обов\'язкове — його замінює доказ. Скрипт вирізає фрагмент за якорями (`count == 1`) '
      'і вставляє **ті самі байти**; перед записом і після нього звіряє `md5(вирізане) == md5(вставлене)`; '
      'після пушу — `G21` ✓ на репо (номер з тілом рівно в одному файлі). Погодження лишається, але предмет '
      'інший: у мікроскопі — межі фрагмента (якорі · байти · звідки · куди), не його текст. Змінено хоч один '
      'байт (формулювання «під новий дім», заголовок усередині фрагмента) — це вже правка, і межа діє без '
      'винятку. **Чому:** межа захищає зміст від втрати й псування; для незмінного переносу md5 доводить це '
      'сильніше за око і нічого не коштує, а читання ~50 KB коштує чату. Прецедент механізму — С2 '
      '(G-K, `655521b`: 8 414 B, md5 звірено до і після запису).\n')
A2 = 'Скрипта в ході немає, а файл канону змінено → ✗ «правка в контексті».\n'
N2 = (' Перенос за винятком Ф-14 без `assert md5(вирізане) == md5(вставлене)` **вище** першого запису → '
      '✗ «перенос без доказу», діє межа.\n')

t = open(P, encoding='utf-8').read()
if t.count(N1) == 1 and t.count(A2.rstrip('\n') + N2) == 1:
    print('✓ вже застосовано — нічого не пишу'); sys.exit(0)
for k, s in (('A1', A1), ('A2', A2)):
    if t.count(s) != 1: die(f'якір {k} count={t.count(s)}')
if 'Ф-14' in t: die('Ф-14 уже згадано у файлі — змішаний стан')
i1 = t.index(A1); i2 = t.index(A2)
if not i1 < i2 or t.rfind('## 12.16', 0, i1) < t.rfind('\n## ', 0, i1): die('якорі поза секцією 12.16')
t2 = t.replace(A1, A1 + N1).replace(A2, A2.rstrip('\n') + N2)
open(P, 'w', encoding='utf-8').write(t2)
print(f'✓ gov-протокол {len(t.encode())} → {len(t2.encode())} B (+Ф-14 у 12.16, +рядок детектора)')
