#!/usr/bin/env python3
# G-C · група Б · Г-10 урізаний → 1.19 (доповнення) · `2.13` → wsd 2.13 · Д-10 урізаний → wsd 2.14
# живе доки: G-C закрито й запушено (пакет сесії, потім архів)
import sys, hashlib
W = "kernel/wsd/Work_Standard.md"; B = "kernel/wsd/wsd_delta_running.md"
w = open(W, encoding="utf-8").read(); b = open(B, encoding="utf-8").read()
md5 = lambda s: hashlib.md5(s.encode()).hexdigest()[:8]
def cut(s, head, nxt):
    assert s.count(head) == 1 and s.count(nxt) == 1, f"якір {head[:30]}/{nxt[:30]} — стоп"
    i = s.index(head); j = s.index(nxt); assert i < j; return s[i:j]

MW1 = "### 1.19-б · Оголошений дім із власним буфером — доставка покажчиком"
MW2 = "## 2.13 Вирок, знятий на зовнішньому ресурсі, — умовний вирок"
MW3 = "## 2.14 Симптом, чутливий до масштабу стенда, — артефакт стенда, доки не відтворений на 1:1"
MB = "| Г-10 «дім названий» ≠ рядок у файлі |"
done = [m in w for m in (MW1, MW2, MW3)] + [MB in b]
if all(done): print("no-op", md5(w), md5(b)); sys.exit(0)
assert not any(done), f"частковий стан {done} — стоп"
print("до", md5(w), md5(b))

H_G10 = "## Г-10 · «Записав» — це рядок у файлі; «дім названий» — ще не рядок у файлі\n"
H_D7 = "## Д-7 · Нова візуальна ідея звіряється з `Lens_cookbook_INDEX.md` ДО пропозиції\n"
H_D10 = "## Д-10 · Симптом, чутливий до масштабу стенда, — артефакт стенда, доки не відтворений на 1:1\n"
H_D8 = "## Д-8 · Device-тест дефектної збірки не є тестом — вирок анулюється явно\n"
H_213 = "## `2.13` (cand.) · Вирок, знятий на зовнішньому ресурсі, — умовний вирок\n"
H_115 = "## ✅ `1.15` (доповнення) · Пастка 4 — ЗМЕРДЖЕНО 03.09.2026 (wsd v2.34)\n"
g10 = cut(b, H_G10, H_D7); d10 = cut(b, H_D10, H_D8); r213 = cut(b, H_213, H_115)
def part(s, a, z=None):
    assert s.count(a) == 1, f"фрагмент {a[:30]} — стоп"
    i = s.index(a)
    if z is None: return s[i:]
    assert s.count(z) == 1, f"фрагмент {z[:30]} — стоп"; return s[i:s.index(z)]

# ── Г-10 → 1.19-б
t2 = part(g10, "**Тригер 2 (новий).**", "**Детектор (К2) — `G12`")
t2 = t2.replace("**Тригер 2 (новий).**", "**Тригер.**")
det = part(g10, "**Детектор (К2) — `G12`", "**Провенанс.**")
det = det.replace("**Детектор (К2) — `G12`, кандидат у `Lens_validate.py`.**",
                  "**Детектор (К2) — кандидат `G18` у `Lens_validate.py`** (коду немає; `G12` зайнятий файлами-мостами, `G17` — `IDX-11`; колізію `Г-12'` розведено G-C 17.09.2026).")
prov = part(g10, "**Провенанс.**", "\n---")
S119 = ("\n\n" + MW1 + "\n\n" + t2 + det +
 "**Розмежування.** `1.19` каже: знання їде у вічний файл **у тій самій сесії**. `13.2-б` (детектор 2) каже: "
 "оголошення «занесу» без diff = не занесено — це вихідний тригер `Г-10` (дієслово запису без дії з файлом). "
 "Тут — лише випадок, коли дім **має власний буфер**: доставкою є покажчик у лотку, не повний текст і не рядок «Дім:» у самері. "
 "Порізно не читаються: `1.19` — куди, `1.19-б` — чим доставлено.\n\n"
 + prov.rstrip() + " Злито G-C 17.09.2026 (урізаний за `12.18`).\n")
A119 = "*(Прецедент `14.31` — GlassKit, EquipLens S11→S15.)*"
assert w.count(A119) == 1; w = w.replace(A119, A119 + S119)

# ── 2.13 і 2.14 → кінець кластера 2
b213 = r213[len(H_213):].rstrip().rstrip("-").rstrip() + "\n"
b213 = b213.replace("*(Народилось: EquipLens S32, 31.08.2026.", "*(Народилось: EquipLens S32, 31.08.2026; злито G-C 17.09.2026.")
d10body = part(d10, "**Джерело:**", "**Детектор (К2).**")
S214 = ("## 2.14 Симптом, чутливий до масштабу стенда, — артефакт стенда, доки не відтворений на 1:1\n\n" + d10body +
 "**Детектор (К2).** Сама вимога індикатора масштабу — `Lens_stagebench_manifest.md` §7 п.4, тут не дублюється. "
 "Власне цього правила: у стенді, що масштабує сцену, біля індикатора друкується **умова дійсності** — "
 "`ЗУМ NN% · скло тільки 1:1` — у **лічильнику** (там, де інші вироки верстки), не в коментарі й не в нотатці, "
 "і оновлюється в тому ж кадрі, що масштаб. Реалізовано: `EquipLens_headbench_v17_21` — `measure()` + виклик із `applyZoom()`.\n\n"
 "**Розмежування.** §7 п.4 каже: показати, **який** масштаб. `2.14` каже: на дробовому масштабі кромковий симптом "
 "**не є дефектом продукту** і в чергу не заводиться. `2.11` уже цитує наслідок для motion. Сусіди: `2.9` · `2.12` · `2.13` — умови дійсності вироку.\n\n"
 "*(Злито G-C 17.09.2026 з буфера `Д-10`, урізаний за `12.18`.)*\n")
AC3 = "\n-----\n\n# Кластер 3 — Pre-patch protocol"
assert w.count(AC3) == 1
w = w.replace(AC3, "\n-----\n\n" + MW2 + "\n\n" + b213 + "\n-----\n\n" + S214 + AC3)

# ── буфер: прибрати три записи, дописати ✅-таблицю, ЛОТОК 8 → 5
for blk in (g10, d10, r213): b = b.replace(blk, "")
L_OLD = "**ЛОТОК: 8 записів.** *(2 покажчики: З-42 · В-15 + 6 повних: Г-10 · Д-7 · Д-8 · Д-9 · Д-10 · `2.13` · G-C група А 17.09.2026: Г-8 · Г-12 погашені ·"
L_NEW = "**ЛОТОК: 5 записів.** *(2 покажчики: З-42 · В-15 + 3 повних: Д-7 · Д-8 · Д-9 · G-C 17.09.2026: А Г-8 · Г-12 погашені · Б Г-10 → 1.19-б · `2.13` → 2.13 · Д-10 → 2.14 ·"
ROW_ANCH = "Дім виявився не `Work_Standard`, а маршрутизатор:"
assert b.count(L_OLD) == 1 and b.count(ROW_ANCH) == 1
b = b.replace(L_OLD, L_NEW)
b = b.replace(ROW_ANCH,
 "**Група Б — злито (урізані за 12.18 / як є):**\n\n| запис | став у wsd | урізано |\n|---|---|---|\n"
 + MB + " **1.19-б** | тригер 1 → `1.19` + `13.2-б` дет. 2; детектор `G12` → кандидат `G18` |\n"
 "| `2.13` (cand.) умовний вирок | **2.13** | нічого |\n"
 "| Д-10 масштаб стенда | **2.14** | вимога індикатора → stagebench §7 п.4 |\n\n" + ROW_ANCH)
open(W, "w", encoding="utf-8").write(w); open(B, "w", encoding="utf-8").write(b)
print("після", md5(w), md5(b))
