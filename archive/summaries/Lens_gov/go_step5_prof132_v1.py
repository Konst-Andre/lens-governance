"""G-O крок 5 — §0 п.4 (знахідка G-N): дубль 13.2 у Lens_PROFILE.md §4 → вказівник на §7 13.2.
   живе доки: хід 5 сесії G-O не влитий у репо.
   12.16: §4 (1 620 B) і тіло 13.2 з 13.2-б (7 857 B) прочитано цілком.
   Це не просто дубль, а СУПЕРЕЧНІСТЬ: пункт §4 дає стару форму «💡 Ідея для [X]: [що саме]. Додати?» —
   саме її 13.2 наводить як анти-приклад (без жанру, дому, ціни); і забороняє ідеї «про поточну задачу» —
   межу, яку 13.2-б явно зняв. Правка — той самий клас, що G-N хід 4 (12.18): конспект → вказівник.
   §7 не чіпається (md5 перевіряється до й після). Ф-20: доказ позиційний.
   П34/П37: повтор → exit 0, жодного запису, той самий md5."""
import sys, hashlib
P = sys.argv[1] if len(sys.argv) > 1 else '/home/claude/lgp/kernel/Lens_PROFILE.md'
def die(m): print('✗ СТОП:', m); sys.exit(1)
OLD = ("- **Проактивні пропозиції** (wsd 13.2): помітив конкретну ідею для протоколу — в кінець відповіді\n"
       "  рядком `💡 Ідея для [X]: [що саме]. Додати?`. Фільтр: тільки конкретне, що економить час\n"
       "  або запобігає помилці. Максимум 1 на відповідь. НЕ всередині технічного блоку.\n"
       "  НЕ якщо ідея стосується лише поточної задачі.\n")
NEW = "- **Проактивні пропозиції «💡»** — тіло правила: §7 `13.2` (родини П і Р — `13.2-б`).\n"
t = open(P, encoding='utf-8').read()
md = lambda s: hashlib.md5(s.encode()).hexdigest()[:8]
s7 = lambda s: md(s[s.index('## §7'):])
if t.count(NEW) == 1 and t.count(OLD) == 0:
    print(f'✓ вже застосовано (md5 {md(t)}) — нічого не пишу'); sys.exit(0)
if not (t.count(OLD) == 1 and t.count(NEW) == 0): die(f'стан змішаний OLD={t.count(OLD)} NEW={t.count(NEW)}')
k = t.index(OLD)
if k > t.index('## §5') or k < t.index('## §4'): die('якір не в §4')
t2 = t[:k] + NEW + t[k + len(OLD):]
if t2[:k] + OLD + t2[k + len(NEW):] != t: die('Ф-20: позиційний revert ≠ old')
if s7(t) != s7(t2): die('§7 змінився')
if t2.count('Ідея для [X]'): die('залишок старої форми')
open(P, 'w', encoding='utf-8').write(t2)
print(f'✓ Ф-20: revert == old · позиція {k} · §7 md5 {s7(t)} незмінний')
print(f'✓ Lens_PROFILE.md {len(t.encode())} → {len(t2.encode())} B · md5 {md(t)} → {md(t2)}')
