#!/usr/bin/env python3
# G-C · група А · Г-8 і Г-12 погашені (12.17) Lens_INDEX §5 «Черги продуктів» → прибрати з буфера
# живе доки: G-C закрито й запушено (пакет сесії, потім архів)
import sys, hashlib
P = sys.argv[1] if len(sys.argv) > 1 else "kernel/wsd/wsd_delta_running.md"
t = open(P, encoding="utf-8").read()
md5 = lambda s: hashlib.md5(s.encode()).hexdigest()[:8]

MARK = "## ✅ G-C · погашені 12.17 — Г-8 · Г-12 (17.09.2026)"
G8 = ("## Г-8 · Черга, числа й специфікації живуть в одному файлі — покажчик\n\n"
      "**Дім:** `Work_Standard`, кластер про самері (сусід **1.8**).\n"
      "**Повний текст:** `EquipLens_S17_STARTPOINTS_and_QUEUE_v7.md` §22 · 25.08.2026.\n\n---\n\n")
G12_HEAD = "## Г-12 · Черга живе в окремому адресованому файлі, не в розділі великого — покажчик\n"
G12_END = "`Lens_INDEX §5`. Детектор — `G14` (не `G12`/`G13`: зайняті).\n\n-----\n\n"
L_OLD = "**ЛОТОК: 10 записів.** *(4 покажчики: Г-8 · З-42 · В-15 · Г-12 + 6 повних: Г-10 · Д-7 · Д-8 · Д-9 · Д-10 · `2.13` ·"
L_NEW = "**ЛОТОК: 8 записів.** *(2 покажчики: З-42 · В-15 + 6 повних: Г-10 · Д-7 · Д-8 · Д-9 · Д-10 · `2.13` · G-C група А 17.09.2026: Г-8 · Г-12 погашені ·"
BLOCK = (MARK + "\n\n"
 "| запис | погашено чим (12.17) | залишок |\n|---|---|---|\n"
 "| Г-8 черга в одному файлі | `Lens_INDEX.md` §5 «Черги продуктів» — абзац «Чому окремим файлом, а не розділом супутника» прямо цитує `Г-8` і причину його відмови | немає |\n"
 "| Г-12 черга в окремому адресованому файлі | `Lens_INDEX.md` §5 «Черги продуктів» — `<Продукт>_CHERGA.md`, стеля 8 KB (число канонічне там, `IDX-10`), без редакцій, покажчик + вік, прецедент `К11`/`К12`; детектор `G14` — борг `IDX-9` | немає |\n\n"
 "Дім виявився не `Work_Standard`, а маршрутизатор: правило про те, **де живе черга**, — роль індексу (`12.11`). Дубль у wsd не заводиться.\n\n---\n\n")

if MARK in t:
    assert G8 not in t and G12_HEAD not in t and L_NEW in t, "частковий стан — стоп"
    print("no-op", md5(t)); sys.exit(0)
for name, a in [("G8", G8), ("G12_HEAD", G12_HEAD), ("G12_END", G12_END), ("LOTOK", L_OLD)]:
    n = t.count(a); assert n == 1, f"якір {name}: count={n} — стоп"
print("до", md5(t))
i = t.index(G12_HEAD); j = t.index(G12_END, i) + len(G12_END)
t = t[:i] + t[j:]
t = t.replace(G8, BLOCK).replace(L_OLD, L_NEW)
open(P, "w", encoding="utf-8").write(t)
print("після", md5(t))
